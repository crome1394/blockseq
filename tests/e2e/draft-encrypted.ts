import puppeteer from "npm:puppeteer-core@23.11.1";
const S = Deno.args[0];
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const BASE = "http://127.0.0.1:3939";
const PW = "correct horse battery";
const name = "DraftEnc2 " + Date.now();
const sh = (cmd: string) => new Deno.Command("bash", { args: ["-c", cmd] }).outputSync();
const browser = await puppeteer.launch({ executablePath: Deno.env.get("CHROME") ?? "/usr/bin/google-chrome-stable", headless: true, args: ["--no-sandbox"] });
const p = await browser.newPage();
p.on("pageerror", (e) => console.log("PAGEERROR:", e.message));
await p.goto(`${BASE}/#/page/${encodeURIComponent(name)}`, { waitUntil: "load" });
await p.waitForSelector(".outline .content"); await sleep(300);
await p.click("#lock-toggle"); await p.waitForSelector(".modal input[type=password]");
await p.type(".modal input[type=password]", PW); await p.keyboard.press("Enter"); await sleep(2500);
await p.click(".outline .content"); await p.keyboard.type("Vault #Encrypted"); await sleep(300); await p.keyboard.press("Escape"); await p.keyboard.press("Enter"); await p.keyboard.press("Tab");
await p.keyboard.type("first secret"); await sleep(1500);
sh("kill $(ss -ltnp | grep ':3939 ' | grep -o 'pid=[0-9]*' | cut -d= -f2)"); await sleep(500);
await p.keyboard.type(" hunter2 typed offline"); await sleep(2500);
const stored = await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith("blockseq.draft:")).map((k) => localStorage.getItem(k)).join("\n"));
console.log("draft exists:", stored.length > 0, "| has plaintext:", stored.includes("hunter2") || stored.includes("first secret"), "| has ciphertext:", stored.includes("encrypted:: v1:"));
sh(`(BLOCKSEQ_DATA=${S}/data BLOCKSEQ_ADDR=127.0.0.1:3939 nohup ${Deno.env.get("BLOCKSEQ_BIN") ?? "./target/debug/blockseq"} > ${S}/server.log 2>&1 &)`);
await sleep(6000);
const left = await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith("blockseq.draft:")).length);
console.log("after the server came back, drafts left:", left, "| server plaintext:", JSON.stringify(await (await fetch(`${BASE}/api/page?name=${encodeURIComponent(name)}`)).json()).includes("hunter2"));
await browser.close();
