import puppeteer from "npm:puppeteer-core@23.11.1";
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const BASE = "http://127.0.0.1:3939";
const name = "Strike " + Date.now();
await fetch(`${BASE}/api/page?name=${encodeURIComponent(name)}`, { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify({ base_version: 0, blocks: [{ id: `s${Date.now()}a`, parent_id: null, content: "TODO Order seeds #garden #task", collapsed: false }, { id: `s${Date.now()}b`, parent_id: null, content: "second line here", collapsed: false }] }) });
const browser = await puppeteer.launch({ executablePath: Deno.env.get("CHROME") ?? "/usr/bin/google-chrome-stable", headless: true, args: ["--no-sandbox"] });
const p = await browser.newPage();
p.on("pageerror", (e) => console.log("PAGEERROR:", e.message));
await p.goto(`${BASE}/#/page/${encodeURIComponent(name)}`, { waitUntil: "load" });
await p.waitForSelector(".outline .content"); await sleep(500);
const bullet = (await p.$$(".outline > .block > .block-row .bullet"))[0];
const bx = (await bullet.boundingBox())!;
await p.mouse.click(bx.x + bx.width / 2, bx.y + bx.height / 2, { button: "right" }); await sleep(400);
await p.evaluate(() => ([...document.querySelectorAll(".menu .item")].find((b) => /Strikethrough/.test(b.textContent || "")) as HTMLElement).click());
await sleep(1500);
await p.click(".outline > .block:nth-child(2) .block-row .content"); await sleep(300);
await p.keyboard.down("Control"); await p.keyboard.down("Shift"); await p.keyboard.press("KeyX"); await p.keyboard.up("Shift"); await p.keyboard.up("Control");
await p.keyboard.press("Escape"); await p.keyboard.press("Escape"); await sleep(1500);
const blocks = (await (await fetch(`${BASE}/api/page?name=${encodeURIComponent(name)}`)).json()).blocks.map((b: any) => b.content);
console.log("menu:", JSON.stringify(blocks[0]));
console.log("shortcut:", JSON.stringify(blocks[1]));
console.log("rendered:", await p.$$eval(".outline del", (d: any[]) => d.length));
await browser.close();
